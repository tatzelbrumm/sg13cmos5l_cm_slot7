"""Committed (old) vs re-run (new) CACE schematic results of sg13cmos5l_IOPadDiff2Single, per group and quantity.

For every quantity of every group: min / median / max over the runs of the group, old and new, in the display unit
of the yaml (the scale of the SI CSV value to that unit is inferred from the new summary_<group>.md, or the old one
if the new results have none, as
datasheets/tools/make_datasheet.py does: the CSV unit labels are unreliable), the relative change of each, and the
largest per-run change over the runs with equal conditions (old and new grids are the same). Changes > 2 % are
flagged. Old mm_params has no per-run data (header-only CSV): its min / typ / max are those of the committed
summary_mm_params.md (typ = CACE's median).
Usage: compare.py <cell.yaml> <old_results_dir> <new_results_dir> <out.md> <out.csv> [<group> ...]
CSV files may start with '#' comment lines (skipped)."""
import csv, math, os, re, statistics as st, sys
import yaml

FLAG = 2.0
_NUM = re.compile(r"^\s*(-?\d+(?:\.\d+)?(?:[eE][+-]?\d+)?)\s*(.*?)\s*$")
ZW = "​"


def read_csv(p):
    if not os.path.exists(p):
        return None
    with open(p, newline='') as f:
        return list(csv.DictReader(l for l in f if not l.startswith('#')))


def read_summary(p):
    rows, hdr = {}, None
    if not os.path.exists(p):
        return rows
    for l in open(p, encoding='utf-8'):
        if not l.startswith('|'):
            continue
        c = [x.strip().replace(ZW, '') for x in l.strip().strip('|').split('|')]
        if c and c[0] == 'Parameter':
            hdr = c
            continue
        if set(''.join(c)) <= set(':-'):
            continue
        if hdr and len(c) == len(hdr):
            r = dict(zip(hdr, c))
            if 'Skip' not in r.get('Status', ''):
                rows[r['Result']] = r
    return rows


def pv(t):
    m = _NUM.match(t or '')
    return (float(m.group(1)), m.group(2)) if m else (None, '')


def scale(vals, smin, smax):
    tol = lambda x: max(0.0006, 0.006 * abs(x))
    for k in (1, 1e3, 1e6, 1e9, 1e12, 1e-3, 1e-6, 1e-9, 1e-12, 1e2, 1e-2):
        if abs(min(vals) * k - smin) <= tol(smin) and abs(max(vals) * k - smax) <= tol(smax):
            return k
    return None


def rel(o, n):
    if o is None or n is None:
        return None
    if o == 0:
        return 0.0 if n == 0 else math.inf
    return 100.0 * (n - o) / abs(o)


def f(v):
    return '—' if v is None else f'{v:.4g}'


def fp(v):
    if v is None:
        return '—'
    if math.isinf(v):
        return 'inf'
    return f'{v:+.2f} %'


def key(row, conds):
    out = []
    for c in conds:
        x = row.get(c)
        try:
            out.append(repr(float(x)))
        except (TypeError, ValueError):
            out.append(str(x))
    return tuple(out)


def main(ycell, old, new, omd, ocsv, groups):
    y = yaml.safe_load(open(ycell))
    P = y['parameters']
    groups = groups or list(P)
    L = ['<!-- SPDX-FileCopyrightText: 2026 Christoph Maier -->', '<!-- SPDX-License-Identifier: Apache-2.0 -->',
         '<!-- generated by compare.py -->',
         '| group | quantity | unit | old min | new min | Δ min | old median | new median | Δ median | old max | new max | Δ max | max per-run Δ (at) | max per-run \\|Δ\\| | runs old / new | flag |',
         '|---|---|---|---:|---:|---:|---:|---:|---:|---:|---:|---:|---|---:|---|---|']
    C = [['group', 'quantity', 'unit', 'old_min', 'new_min', 'd_min_pct', 'old_median', 'new_median', 'd_median_pct',
          'old_max', 'new_max', 'd_max_pct', 'max_run_d_pct', 'max_run_at', 'max_run_abs_d', 'runs_old', 'runs_new', 'flag']]
    for g in groups:
        spec = P[g]
        conds = list((spec.get('conditions') or {}).keys())
        variables = spec['tool']['ngspice']['variables']
        do, dn = read_csv(os.path.join(old, f'{g}.csv')), read_csv(os.path.join(new, f'{g}.csv'))
        so, sn = read_summary(os.path.join(old, f'summary_{g}.md')), read_summary(os.path.join(new, f'summary_{g}.md'))
        if dn is None:
            L.append(f'| {g} | (not run) | | | | | | | | | | | | | | |')
            continue
        for q in spec['spec']:
            disp = spec['spec'][q].get('display', q)
            unit = spec['spec'][q].get('unit', '')
            col = next((c for c in (dn[0].keys() if dn else []) if c.startswith(q + '[')), None)
            if col is None:
                continue
            nv = [float(r[col]) for r in dn]
            k = None
            for sx, vx in ((sn, nv), (so, [float(r[col]) for r in (do or [])])):
                if k is None and q in sx and vx:
                    smin, _ = pv(sx[q]['Min Value']); smax, _ = pv(sx[q]['Max Value'])
                    if smin is not None and smax is not None:
                        k = scale(vx, smin, smax)
            if k is None:
                k = 1.0
                unit = (unit + ' (CSV value, SI)') if unit else '(CSV value)'
            nv = [v * k for v in nv]
            n3 = (min(nv), st.median(nv), max(nv))
            if do:
                ov = [float(r[col]) * k for r in do]
                o3 = (min(ov), st.median(ov), max(ov))
                om = {key(r, conds): float(r[col]) * k for r in do}
                worst, at, wabs = None, '', None
                for r, v in zip(dn, nv):
                    kk = key(r, conds)
                    if kk in om:
                        d = rel(om[kk], v)
                        if worst is None or abs(d) > abs(worst):
                            worst, at = d, ', '.join(f'{c}={r[c]}' for c in conds if c != 'iterations')
                        if wabs is None or abs(v - om[kk]) > wabs:
                            wabs = abs(v - om[kk])
                nold = len(do)
            elif q in so:
                o3 = tuple(pv(so[q][c])[0] for c in ('Min Value', 'Typ Value', 'Max Value'))
                worst, at, nold, wabs = None, 'old: summary only', 0, None
            else:
                o3, worst, at, nold, wabs = (None, None, None), None, '', 0, None
            ds = [rel(a, b) for a, b in zip(o3, n3)]
            allv = [x for x in ds + [worst] if x is not None]
            flag = 'Δ > 2 %' if any(abs(x) > FLAG for x in allv) else ''
            L.append(f'| {g} | {disp} | {unit} | {f(o3[0])} | {f(n3[0])} | {fp(ds[0])} | {f(o3[1])} | {f(n3[1])} | '
                     f'{fp(ds[1])} | {f(o3[2])} | {f(n3[2])} | {fp(ds[2])} | {fp(worst)}{(" (" + at + ")") if at else ""} | '
                     f'{f(wabs)} | {nold} / {len(dn)} | {flag} |')
            C.append([g, disp, unit] + [x for t in zip(o3, n3, ds) for x in t] + [worst, at, wabs, nold, len(dn), flag])
    open(omd, 'w', encoding='utf-8').write('\n'.join(L) + '\n')
    with open(ocsv, 'w', newline='') as fh:
        fh.write('# SPDX-FileCopyrightText: 2026 Christoph Maier\n# SPDX-License-Identifier: Apache-2.0\n')
        w = csv.writer(fh)
        for r in C:
            w.writerow(['' if x is None else (f'{x:.6g}' if isinstance(x, float) else x) for x in r])
    print(f'{omd}: {len(L) - 5} rows, {sum(1 for r in C[1:] if r[-1])} flagged')


if __name__ == '__main__':
    if len(sys.argv) < 6:
        sys.exit(__doc__)
    main(sys.argv[1], sys.argv[2], sys.argv[3], sys.argv[4], sys.argv[5], sys.argv[6:])
