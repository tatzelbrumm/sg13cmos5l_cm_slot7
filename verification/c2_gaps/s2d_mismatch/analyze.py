"""Statistics, comparison with the committed CACE results, and histograms of the S2D pad's Monte Carlo groups.

Usage: analyze.py <cell.yaml> <committed_results_dir> <csv_dir> <out_dir>
Reads <csv_dir>/<group>[_pex].csv (mm_collect.py format, '#' comment lines) and the CACE summaries
<csv_dir>/summary_<group>[_pex].md of this run, and the committed <committed_results_dir>/summary_<group>.md and
dc_params.csv. Writes <out_dir>/tables/stats.{md,csv}, <out_dir>/tables/compare_committed.md and
<out_dir>/figures/*.png (150 dpi). Every number comes from those files; nothing is typed in.
"""
import csv, os, re, statistics as st, sys
import yaml
import matplotlib
matplotlib.use('Agg')
import matplotlib.pyplot as plt

MC_GROUPS = ('mm_params', 'ac_mm_params', 'mc_params')
VIEWS = (('', 'schematic'), ('_pex', 'magic PEX (C-coupled), mm_ok=1 on the extracted devices'))
SCALE = {'mV': 1e3, 'uV': 1e6, 'V': 1, 'dB': 1, '': 1, 'MHz': 1e-6, 'uA': 1e6, 'nA': 1e9}
BLUE, ORANGE = '#4a6fa5', '#d9822b'


def load(path):
    if not os.path.exists(path):
        return None
    with open(path) as fh:
        return list(csv.DictReader(l for l in fh if not l.startswith('#')))


def col(rows, var):
    for k in rows[0]:
        if k.split('[')[0] == var:
            return [float(r[k]) for r in rows]
    raise KeyError(var)


def summary(path):
    """CACE summary.md -> {display name: (min, typ, max) as printed (strings)}"""
    out = {}
    if not os.path.exists(path):
        return out
    for line in open(path):
        c = [x.strip() for x in line.strip().strip('|').split('|')]
        if len(c) == 10 and c[1] == 'ngspice':
            out[c[0]] = (c[4], c[6], c[8], c[9])
    return out


def num(s):
    """'-17.250 mV' -> (value in SI, unit); '' or the zero-width space of a skipped row -> None"""
    s = s.replace('​', '').strip()
    m = re.match(r'^([-+0-9.eE]+)\s*(\S*)$', s)
    if not m:
        return None
    u = m.group(2)
    return float(m.group(1)) / SCALE.get(u, 1)


def fmt(x, k=4):
    return '%.*g' % (k, x)


def sigma_ci(s, n):
    """95 % confidence interval of sigma for a normal sample (chi-square quantiles by Wilson-Hilferty)"""
    def chi2(p_z, k):
        return k * (1 - 2 / (9 * k) + p_z * (2 / (9 * k)) ** 0.5) ** 3
    k = n - 1
    return s * (k / chi2(1.959964, k)) ** 0.5, s * (k / chi2(-1.959964, k)) ** 0.5


def main(ycell, oldres, csvdir, out):
    y = yaml.safe_load(open(ycell))['parameters']
    os.makedirs(os.path.join(out, 'tables'), exist_ok=True)
    os.makedirs(os.path.join(out, 'figures'), exist_ok=True)
    md, rows_csv, data = [], [], {}
    md.append('<!--\nSPDX-FileCopyrightText: 2026 Christoph Maier\nSPDX-License-Identifier: Apache-2.0\n'
              'generated by analyze.py from csv/*.csv and the CACE summaries; IHP sg13cmos5l simulation\n-->')
    md.append('| group | view | quantity | unit | n (runs with data / runs) | mean | sigma | sigma, 95 % CI | min | median | '
              'max | mean - 3 sigma | mean + 3 sigma | working limits | min / max inside |')
    md.append('|---|---|---|---|---|---:|---:|---|---:|---:|---:|---:|---:|---|---|')
    cmp_ = []
    for g in MC_GROUPS:
        spec = y[g]['spec']
        n_iter = y[g]['conditions']['iterations']['maximum']
        old = summary(os.path.join(oldres, 'summary_%s.md' % g))
        for suf, view in VIEWS:
            rows = load(os.path.join(csvdir, '%s%s.csv' % (g, suf)))
            if not rows:
                continue
            new = summary(os.path.join(csvdir, 'summary_%s%s.md' % (g, suf)))
            for var, sp in spec.items():
                u = sp.get('unit', '')
                k = SCALE.get(u, 1)
                x = col(rows, var)
                data[(g, suf, var)] = x
                m, s = st.mean(x), st.stdev(x)
                lo, hi = sp.get('minimum', {}).get('value', 'any'), sp.get('maximum', {}).get('value', 'any')
                inside = all((lo == 'any' or v * k >= float(lo)) and (hi == 'any' or v * k <= float(hi)) for v in x)
                lim = '%s … %s' % (lo, hi)
                vals = [m * k, s * k, min(x) * k, st.median(x) * k, max(x) * k, (m - 3 * s) * k, (m + 3 * s) * k]
                ci = sigma_ci(s * k, len(x))
                md.append('| %s | %s | %s | %s | %d / %d | %s | %s | %s … %s | %s | %s | %s | %s | %s | %s | %s |' % (
                    g, view.split(',')[0], sp['display'], u, len(x), n_iter, fmt(vals[0]), fmt(vals[1]),
                    fmt(ci[0], 3), fmt(ci[1], 3), *[fmt(v) for v in vals[2:]], lim, 'yes' if inside else '**no**'))
                rows_csv.append([g, 'pex' if suf else 'schematic', var, u, len(x), n_iter] + ['%.6g' % v for v in vals])
                o = old.get(sp['display'])
                nw = new.get(sp['display'])
                cmp_.append((g, 'pex' if suf else 'schematic', sp['display'], u, o, nw,
                             (min(x) * k, st.median(x) * k, m * k, max(x) * k, s * k)))
    # rejection in linear terms: input-referred coupling 10^(-dB/20) (V at the input per V on the supply / common mode)
    acm = [(v, d) for (g, suf, v), d in data.items() if g == 'ac_mm_params' and not suf]
    if acm:
        md += ['', 'ac_mm_params, the same runs as input-referred coupling 10^(-PSRR/20) (µV at the input per V on '
               'iovdd / iovss, or per V of common mode for CMRR): the dB values are skewed (a run near perfect '
               'cancellation gives a very large dB value), the linear coupling is the quantity that adds up.', '',
               '| quantity | n | mean | sigma | median | max (= min in dB) |', '|---|---|---:|---:|---:|---:|']
        for v, d in acm:
            lin = [10 ** (-x / 20) * 1e6 for x in d]
            md.append('| %s | %d | %s µV/V | %s µV/V | %s µV/V | %s µV/V |' % (v, len(lin), fmt(st.mean(lin), 3),
                      fmt(st.stdev(lin), 3), fmt(st.median(lin), 3), fmt(max(lin), 3)))
    # schematic and PEX runs share the seeds (SEED = 12345 + iteration) but not the device list: correlation per seed
    pairs = [v for (g, suf, v) in data if g == 'mm_params' and suf == '_pex']
    if pairs:
        md += ['', 'mm_params, schematic vs PEX run with the same seed: Pearson correlation over the 100 seeds (the '
               'extraction has another device list and order, so the same seed draws other numbers per device).', '',
               '| quantity | correlation |', '|---|---:|']
        for v in pairs:
            a, b = data[('mm_params', '', v)], data[('mm_params', '_pex', v)]
            ma, mb = st.mean(a), st.mean(b)
            r = sum((x - ma) * (y_ - mb) for x, y_ in zip(a, b)) / ((sum((x - ma) ** 2 for x in a) *
                                                                      sum((y_ - mb) ** 2 for y_ in b)) ** 0.5)
            md.append('| %s | %.2f |' % (v, r))
    open(os.path.join(out, 'tables', 'stats.md'), 'w').write('\n'.join(md) + '\n')
    with open(os.path.join(out, 'tables', 'stats.csv'), 'w', newline='') as fh:
        w = csv.writer(fh)
        fh.write('# SPDX-FileCopyrightText: 2026 Christoph Maier\n# SPDX-License-Identifier: Apache-2.0\n'
                 '# values in the yaml display unit (column unit)\n')
        w.writerow(['group', 'view', 'quantity', 'unit', 'n', 'runs', 'mean', 'sigma', 'min', 'median', 'max',
                    'mean-3sigma', 'mean+3sigma'])
        w.writerows(rows_csv)

    # comparison with the committed CACE summaries (2026-10-26 run) and with this run's own CACE summary
    c = ['<!--\nSPDX-FileCopyrightText: 2026 Christoph Maier\nSPDX-License-Identifier: Apache-2.0\n'
         'generated by analyze.py\n-->',
         '### Monte Carlo groups: committed CACE summary (min / typ / max) vs this run',
         '',
         '"this run, CACE" = CACE 2.11\'s own summary of this run (its typ column); "this run, CSV" = from the per-run '
         'CSV: min / median / mean / max.',
         '',
         '| group | view | quantity | unit | committed min / typ / max (status) | this run, CACE min / typ / max (status) | '
         'this run, CSV min / median / mean / max | sigma |',
         '|---|---|---|---|---|---|---|---|']
    for g, view, disp, u, o, nw, v in cmp_:
        so = '%s / %s / %s (%s)' % o if o else '—'
        sn = '%s / %s / %s (%s)' % nw if nw else '—'
        so, sn = so.replace('​', '').replace(' ✅', '').replace(' ❌', ''), sn.replace('​', '').replace(' ✅', '').replace(' ❌', '')
        c.append('| %s | %s | %s | %s | %s | %s | %s | %s |' % (g, view, disp, u, so, sn,
                                                                ' / '.join(fmt(t) for t in v[:4]), fmt(v[4])))
    # dc_params check: every committed run against the same conditions in this run
    newdc, olddc = load(os.path.join(csvdir, 'dc_params.csv')), load(os.path.join(oldres, 'dc_params.csv'))
    if newdc and olddc:
        conds = list(y['dc_params']['conditions'])
        key = lambda r: tuple(str(float(r[k])) if re.match(r'^-?[0-9.]+$', str(r[k])) else r[k] for k in conds)
        nd = {key(r): r for r in newdc}
        c += ['', '### dc_params (check of the committed non-Monte-Carlo schematic results, 2026-11-05)', '',
              'committed `dc_params.csv` (%d runs) vs this run (%d runs), matched by conditions; largest difference '
              'over all matched runs, absolute and relative to the committed value. Values as in the CSVs: SI (V, A), '
              'whatever the [unit] label says.' % (len(olddc), len(newdc)), '',
              '| quantity | matched runs | largest abs. difference | largest rel. difference | committed range | this run range |',
              '|---|---:|---:|---:|---|---|']
        for h in [h for h in olddc[0] if h not in conds]:
            pairs = [(float(r[h]), float(nd[key(r)][h])) for r in olddc if key(r) in nd]
            if not pairs:
                continue
            da = max(abs(b - a) for a, b in pairs)
            dr = max(abs(b - a) / abs(a) for a, b in pairs if a != 0)
            c.append('| %s | %d | %.3g | %.3g %% | %s … %s | %s … %s |' % (h, len(pairs), da, dr * 100,
                     fmt(min(a for a, _ in pairs)), fmt(max(a for a, _ in pairs)),
                     fmt(min(b for _, b in pairs)), fmt(max(b for _, b in pairs))))
    open(os.path.join(out, 'tables', 'compare_committed.md'), 'w').write('\n'.join(c) + '\n')

    # histograms (style of ../replica_bias/results/pad_ref_rb_mc_hist.png), 150 dpi
    def hist(name, g, vars_, title, ncol):
        nrow = (len(vars_) + ncol - 1) // ncol
        fig, ax = plt.subplots(nrow, ncol, figsize=(3.3 * ncol, 2.7 * nrow + 0.5), squeeze=False)
        for a in ax.flat[len(vars_):]:
            a.axis('off')
        views = []
        for a, vk in zip(ax.flat, vars_):
            var, lab, k = vk[:3]
            off = vk[3] if len(vk) > 3 else 0
            xs = data.get((g, '', var))
            xp = data.get((g, '_pex', var))
            allv = [(v - off) * k for v in (xs or []) + (xp or [])]
            lo, hi = min(allv), max(allv)
            bins = [lo + (hi - lo) * i / 20 for i in range(21)] if hi > lo else 20
            txt = []
            un = re.search(r'\[(.*)\]', lab)
            un = ' ' + un.group(1) if un else ''
            if xs:
                a.hist([(v - off) * k for v in xs], bins=bins, color=BLUE, edgecolor='white', label='schematic')
                txt.append('sch: mean %s%s, σ %s%s' % (fmt((st.mean(xs) - off) * k, 4), un, fmt(st.stdev(xs) * k, 3), un))
                views.append('schematic')
            if xp:
                a.hist([(v - off) * k for v in xp], bins=bins, histtype='step', color=ORANGE, linewidth=1.6, label='PEX')
                txt.append('PEX: mean %s%s, σ %s%s' % (fmt((st.mean(xp) - off) * k, 4), un, fmt(st.stdev(xp) * k, 3), un))
                views.append('PEX')
            a.set_xlabel(lab); a.set_ylabel('runs')
            a.set_title('\n'.join(txt), fontsize=7.5)
            if xs and xp:
                a.legend(fontsize=7, frameon=False)
        n = len(data.get((g, '', vars_[0][0])) or [])
        np_ = len(data.get((g, '_pex', vars_[0][0])) or [])
        v = 'schematic (%d runs)' % n + (' and magic PEX with mm_ok=1 (%d runs, orange outline)' % np_ if np_ else '')
        fig.suptitle('%s\nIHP sg13cmos5l simulation, %s' % (title, v), fontsize=9)
        fig.tight_layout()
        p = os.path.join(out, 'figures', name)
        fig.savefig(p, dpi=150); plt.close(fig)
        print('%s: %d kB' % (p, os.path.getsize(p) // 1024))

    if (('mm_params', '', 'Vos_in')) in data:
        hist('s2d_mm_hist.png', 'mm_params', [('Vos_in', 'input offset [mV]', 1e3), ('Gain', 'gain (outp − outn)/u', 1),
                                              ('Vcm_err', 'output CM error [mV]', 1e3)],
             'S2D pad, local-mismatch MC (CACE mm_params), tt_mismatch / rhigh typ_mismatch, 27 °C, 3.3 V', 3)
    if (('ac_mm_params', '', 'PSRRp_1k')) in data:
        hist('s2d_ac_mm_hist.png', 'ac_mm_params', [('PSRRp_1k', 'PSRR iovdd 1 kHz [dB]', 1),
                                                    ('PSRRp_100k', 'PSRR iovdd 100 kHz [dB]', 1),
                                                    ('CMRR_1k', 'CMRR 1 kHz [dB]', 1),
                                                    ('PSRRn_1k', 'PSRR iovss 1 kHz [dB]', 1),
                                                    ('PSRRn_100k', 'PSRR iovss 100 kHz [dB]', 1)],
             'S2D pad, rejection under local mismatch (CACE ac_mm_params), input-referred, 27 °C, 3.3 V', 3)
    if (('mc_params', '', 'Vcm_err')) in data:
        hist('s2d_mc_hist.png', 'mc_params', [('Vos_in', 'input offset [nV]', 1e9),
                                              ('Gain', 'gain − 2 [ppm] (printed to 10 ppm)', 1e6, 2.0),
                                              ('Vcm_err', 'output CM error [mV]', 1e3)],
             'S2D pad, process MC (CACE mc_params), tt_stat / rhigh typ, 27 °C, 3.3 V', 3)


if __name__ == '__main__':
    if len(sys.argv) != 5:
        sys.exit(__doc__)
    main(*sys.argv[1:])
